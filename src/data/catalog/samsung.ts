type SVariant = "base" | "edge" | "edgePlus" | "plus" | "ultra" | "fe";

function GalaxyS(
  slug: string,
  name: string,
  year: number,
  gen: SGen,
  variant: SVariant,
  opts: { mAh?: number; ecran?: number } = {},
): Device {
  const t = SGEN[gen];
  const isEdge = variant === "edge" || variant === "edgePlus";
  const screen =
    opts.ecran ??
    (variant === "ultra"
      ? t.ecranUltra
      : isEdge || variant === "plus"
        ? t.ecranPlus
        : variant === "fe"
          ? t.ecranFe
          : t.ecran);
  const mAh =
    opts.mAh ??
    (variant === "ultra"
      ? t.mAhUltra
      : isEdge || variant === "plus"
        ? t.mAhPlus
        : variant === "fe"
          ? t.mAhFe
          : t.mAh);
  const bat = variant === "ultra" ? t.batUltra : t.bat;
  const connPrice = variant === "ultra" ? t.connUltra : t.conn;
  const isMicro = gen === "s6" || gen === "s7";
  const isOld = gen === "s6" || gen === "s7";
  const isS8S9 = gen === "s8" || gen === "s9";
  const isS10 = gen === "s10";
  const screenLabel = isEdge
    ? "Écran Super AMOLED incurvé"
    : variant === "fe" && t.feLabel
      ? t.feLabel
      : t.label;
  const ecranDur = variant === "ultra" && !isS10 ? "50 min" : isOld ? "40 min" : "45 min";
  const ecranPart = isOld ? "Écran service pack" : "Écran service pack Samsung";
  const connDur = isOld ? "40 min" : isS8S9 ? "40 min" : isS10 ? "40 min" : "45 min";
  const connWarranty = isOld ? "1 mois" : "3 mois";
  const faults: Fault[] = [
    f("ecran", screenLabel, screen, ecranDur, "6 mois", ecranPart),
    f(
      "batterie",
      `Batterie ${mAh} mAh`,
      bat,
      isOld ? "35 min" : "40 min",
      "6 mois",
      "Batterie service pack",
    ),
    f(
      "connecteur",
      isMicro ? "Micro-USB" : "Port USB-C",
      connPrice,
      connDur,
      connWarranty,
      "Nappe de charge",
    ),
  ];
  if (variant === "ultra") {
    if (t.camUltra)
      faults.push(
        f("camera", "Bloc caméra arrière", t.camUltra, "70 min", "6 mois", "Module capteur"),
      );
    if (t.vitreUltra)
      faults.push(
        f("vitre-arriere", "Vitre arrière", t.vitreUltra, "60 min", "1 mois", "Verre + adhésif"),
      );
  } else if (variant === "fe") {
    if (t.feCam)
      faults.push(
        f("camera", "Bloc caméra arrière", t.feCam, "70 min", "6 mois", "Module capteur"),
      );
    if (t.feVitre)
      faults.push(
        f("vitre-arriere", "Vitre arrière", t.feVitre, "60 min", "1 mois", "Verre + adhésif"),
      );
  } else {
    if (t.cam)
      faults.push(f("camera", "Bloc caméra arrière", t.cam, "70 min", "6 mois", "Module capteur"));
    if (t.vitre)
      faults.push(
        f("vitre-arriere", "Vitre arrière", t.vitre, "60 min", "1 mois", "Verre + adhésif"),
      );
  }
  return { slug, name, brand: "samsung", series: "Galaxy S", category: "Smartphone", year, faults };
}

