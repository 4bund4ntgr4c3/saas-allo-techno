type PhoneSpec = {
  screen: string;
  ecran: number;
  mAh: number;
  bat: number;
  conn: "micro" | "usbc";
  connPrice: number;
  cam?: number;
  camLabel?: string;
  vitre?: number;
  hp?: number;
  desox?: number;
  old?: boolean;
};

function Phone(slug: string, name: string, year: number, series: string, spec: PhoneSpec): Device {
  const faults: Fault[] = [
    f(
      "ecran",
      spec.screen,
      spec.ecran,
      spec.old ? "35 min" : "40 min",
      "6 mois",
      spec.old ? "Écran service pack" : "Écran service pack Samsung",
    ),
    f(
      "batterie",
      `Batterie ${spec.mAh} mAh`,
      spec.bat,
      spec.old ? "30 min" : "35 min",
      "3 mois",
      "Batterie service pack",
    ),
    f(
      "connecteur",
      spec.conn === "micro" ? "Micro-USB" : "Port USB-C",
      spec.connPrice,
      spec.old ? "40 min" : "45 min",
      spec.old ? "1 mois" : "3 mois",
      "Nappe de charge",
    ),
  ];
  if (spec.cam)
    faults.push(
      f(
        "camera",
        spec.camLabel ?? "Bloc caméra arrière",
        spec.cam,
        "70 min",
        "6 mois",
        "Module capteur",
      ),
    );
  if (spec.vitre)
    faults.push(
      f("vitre-arriere", "Vitre arrière", spec.vitre, "60 min", "1 mois", "Verre + adhésif"),
    );
  if (spec.hp)
    faults.push(
      f("haut-parleur", "Haut-parleur / écouteur", spec.hp, "45 min", "3 mois", "Module audio"),
    );
  if (spec.desox)
    faults.push(f("desoxydation", "Désoxydation", spec.desox, "48 h", "1 mois", "Bain ultrasons"));
  return { slug, name, brand: "samsung", series, category: "Smartphone", year, faults };
}

